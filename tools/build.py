#!/usr/bin/env python3
"""Build Hornbill Express into dist/ for GitHub Pages (or any static host).

- copies the game files
- checks that every local file referenced by the HTML pages exists
- writes an offline service worker (sw.js) with a content-hash version,
  so the booth keeps working if the Wi-Fi drops

Usage:  python tools/build.py            -> dist/
        python tools/build.py --out site -> site/
"""
import argparse
import hashlib
import json
import os
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INCLUDE = ["index.html", "display.html", "manifest.webmanifest", "icon.svg", "css", "js", "vendor"]

SW_TEMPLATE = """// Generated by tools/build.py — do not edit by hand.
const VERSION = '%(version)s';
const FILES = %(files)s;
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(VERSION).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== VERSION && k !== 'fonts').map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET') return;
  const sdk = url.hostname === 'www.gstatic.com' && url.pathname.startsWith('/firebasejs/');
  if (sdk || url.hostname.endsWith('fonts.googleapis.com') || url.hostname.endsWith('fonts.gstatic.com')) {
    e.respondWith(caches.open('fonts').then((c) => c.match(e.request).then((hit) => hit || fetch(e.request).then((res) => { c.put(e.request, res.clone()); return res; }))));
    return;
  }
  if (url.origin !== location.origin) return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request)));
});
"""


def local_refs(html: str):
    for m in re.finditer(r'(?:src|href)="([^"#?]+)', html):
        ref = m.group(1)
        if ref.startswith(("http:", "https:", "data:", "mailto:", "//")):
            continue
        yield ref


def js_imports(js: str):
    for m in re.finditer(r"""(?:import|from)\s*['"](\.[^'"]+)['"]""", js):
        yield m.group(1)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="dist")
    args = ap.parse_args()
    out = (ROOT / args.out).resolve()
    if out == ROOT:
        sys.exit("Refusing to build into the project root")
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)

    for name in INCLUDE:
        src = ROOT / name
        if src.is_dir():
            shutil.copytree(src, out / name)
        else:
            shutil.copy2(src, out / name)

    # Firebase web config: FIREBASE_CONFIG env var (JSON) or firebase.config.json overrides js/firebase-config.js
    cfg = os.environ.get("FIREBASE_CONFIG", "").strip()
    cfg_file = ROOT / "firebase.config.json"
    if not cfg and cfg_file.exists():
        cfg = cfg_file.read_text(encoding="utf-8").strip()
    if cfg:
        try:
            data = json.loads(cfg)
        except json.JSONDecodeError as e:
            sys.exit(f"FIREBASE_CONFIG is not valid JSON: {e}")
        missing = [k for k in ("apiKey", "projectId", "appId") if not data.get(k)]
        if missing:
            sys.exit(f"Firebase config is missing: {', '.join(missing)}")
        (out / "js" / "firebase-config.js").write_text(
            "// Generated by tools/build.py from FIREBASE_CONFIG / firebase.config.json\n"
            f"export const firebaseConfig = {json.dumps(data, indent=2)};\n", encoding="utf-8")
        print(f"Firebase: project {data['projectId']}")
    else:
        print("Firebase: not configured (local storage only)")

    # check references
    problems = []
    for page in ["index.html", "display.html"]:
        for ref in local_refs((out / page).read_text(encoding="utf-8")):
            if not (out / ref).exists():
                problems.append(f"{page}: missing {ref}")
    for js in (out / "js").glob("*.js"):
        for ref in js_imports(js.read_text(encoding="utf-8")):
            if not (js.parent / ref).resolve().exists():
                problems.append(f"{js.name}: missing import {ref}")
    if problems:
        print("\n".join(problems))
        sys.exit(1)

    files = sorted(str(p.relative_to(out)).replace("\\", "/") for p in out.rglob("*") if p.is_file())
    digest = hashlib.sha256()
    for f in files:
        digest.update(f.encode())
        digest.update((out / f).read_bytes())
    version = "hornbill-" + digest.hexdigest()[:10]
    cached = ["./"] + files
    (out / "sw.js").write_text(SW_TEMPLATE % {"version": version, "files": json.dumps(cached)}, encoding="utf-8")
    (out / ".nojekyll").write_text("", encoding="utf-8")
    print(f"Built {len(files) + 1} files into {out} ({version})")


if __name__ == "__main__":
    main()
